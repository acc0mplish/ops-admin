export const locale = ref(KOREAN_LOCALE)

// 한국어를 제품의 canonical locale로 사용한다. 기존 브라우저에 저장된 zh-CN/en-US 값도
// 자동으로 ko-KR로 정규화해 포크 원본의 언어 설정이 남지 않도록 한다.
if (localStorage.getItem(LOCALE_KEY) !== KOREAN_LOCALE) {
  localStorage.setItem(LOCALE_KEY, KOREAN_LOCALE)
}

export function setLocale() {
  locale.value = KOREAN_LOCALE
  localStorage.setItem(LOCALE_KEY, KOREAN_LOCALE)
}

export function getLocale() {
  return KOREAN_LOCALE
}

export function t(key, params = {}) {
  let text = ko[key] || key
  Object.keys(params).forEach((name) => {
    text = text.replaceAll(`{${name}}`, String(params[name]))
  })
  return text
}

