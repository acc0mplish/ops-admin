export function uiT(key, params = {}) {
  const dictionary = currentLocale.value === 'en-US' ? en : ko
  let text = dictionary[key] || en[key] || key
  Object.entries(params).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value))
  })
  return text
}
